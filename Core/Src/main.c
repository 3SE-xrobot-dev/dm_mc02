{
  if (frequency_hz == 0U || volume_percent == 0U)
  {
    __HAL_TIM_SET_COMPARE(&htim12, TIM_CHANNEL_2, 0);
    return HAL_OK;
  }
  if (frequency_hz < 20U || frequency_hz > 20000U || volume_percent > 100U)
  {
    return HAL_ERROR;
  }

  uint32_t period = (1000000U + frequency_hz / 2U) / frequency_hz;
  __HAL_TIM_SET_COMPARE(&htim12, TIM_CHANNEL_2, 0);
  __HAL_TIM_SET_AUTORELOAD(&htim12, period - 1U);
  __HAL_TIM_SET_COUNTER(&htim12, 0);
  __HAL_TIM_SET_COMPARE(&htim12, TIM_CHANNEL_2, period * volume_percent / 200U);
  return HAL_OK;
}

